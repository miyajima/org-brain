#!/usr/bin/env node

import crypto from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { deriveMemoryCaptureHookProfile } from "../packages/shared/src/memory-capture-profile-runtime.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const DEFAULT_GOLD_DATASET = path.join(ROOT, "packages/shared/test/fixtures/memory-capture-gold-v1.json");
export const DEFAULT_PROFILE_OUTPUT = path.join(ROOT, "packages/shared/src/memory-capture-profile.generated.mjs");

function canonicalize(value) {
  if (Array.isArray(value)) return value.map(canonicalize);
  if (!value || typeof value !== "object") return value;
  return Object.fromEntries(Object.keys(value).sort().map((key) => [key, canonicalize(value[key])]));
}

export function canonicalDatasetJson(dataset) {
  return JSON.stringify(canonicalize(dataset));
}

export function renderMemoryCaptureProfileModule(profile) {
  return [
    "// Generated by scripts/derive-memory-hook-profile.mjs. Do not edit by hand.",
    `export const MEMORY_CAPTURE_HOOK_PROFILE = Object.freeze(${JSON.stringify(profile, null, 2)});`,
    ""
  ].join("\n");
}

export function parseArgs(argv) {
  const options = {
    fixture: DEFAULT_GOLD_DATASET,
    output: DEFAULT_PROFILE_OUTPUT,
    check: false
  };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    const value = () => {
      const next = argv[index + 1];
      if (!next || next.startsWith("--")) throw new Error(`${arg}_value_required`);
      index += 1;
      return path.resolve(next);
    };
    if (arg === "--fixture") options.fixture = value();
    else if (arg === "--output") options.output = value();
    else if (arg === "--check") options.check = true;
    else throw new Error(`unknown_argument:${arg}`);
  }
  return options;
}

export async function buildMemoryCaptureProfile(options) {
  const dataset = JSON.parse(await readFile(options.fixture, "utf8"));
  const datasetSha256 = crypto.createHash("sha256").update(canonicalDatasetJson(dataset)).digest("hex");
  const profile = deriveMemoryCaptureHookProfile(dataset, { dataset_sha256: datasetSha256 });
  return { dataset, profile, rendered: renderMemoryCaptureProfileModule(profile) };
}

export async function main(argv = process.argv.slice(2)) {
  const options = parseArgs(argv);
  const built = await buildMemoryCaptureProfile(options);
  if (options.check) {
    const existing = await readFile(options.output, "utf8").catch(() => "");
    if (existing !== built.rendered) throw new Error("memory_capture_profile_drift");
  } else {
    await writeFile(options.output, built.rendered, "utf8");
  }
  console.log(JSON.stringify({
    ok: true,
    mode: options.check ? "check" : "write",
    profile_id: built.profile.profile_id,
    dataset_sha256: built.profile.source_dataset_sha256,
    output: options.output
  }));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  });
}
